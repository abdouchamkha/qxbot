def arb(lang, i):
    out = {"@@locale": lang}
    for k, v in T.items():
        text = v[i]
        out[k] = text
        if i == 0:
            names = []
            for n in re.findall(r"\{(\w+)[,}]", text):
                if n not in names:
                    names.append(n)
            if names:
                out["@" + k] = {"placeholders": {n: {"type": "int" if n in INTS else "String"} for n in names}}
    return out

